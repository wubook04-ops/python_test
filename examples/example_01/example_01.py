def cluster_and_label(data, create_and_show_plot=True):
    data = StandardScaler().fit_transform(data)
    db = DBSCAN(eps=0.3, min_samples=10).fit(data)
    #从聚类中找到标签
    core_samples_mask = numpy.zeros_like(db.labels_,dtype=bool)
    core_samples_mask[db.core_sample_indices_] = True
    labels = db.labels_

    #标签中的类聚数，如果存在噪声则忽略
    n_cluster_ = len(set(labels)) - (1 if -1 in labels else 0)
    n_noise_ = list(labels).count(-1)

    run_metadata = {
        'nClusters' : n_cluster_,
        'nNoise' : n_noise_,
        'silhouetteCoefficient' :
        metrics.silhouette_score(data, labels),
        'labels' : labels,
    }
    if create_and_show_plot:
        plot_cluster_results(data, labels, core_samples_mask, n_cluster_)
    else:
        pass
    return run_metadata

def plot_cluster_results(data, labels, core_samples_mask, n_clusters_):
    fig = pyplot.figure(figsize=(10, 10))
    #黑色标签被移除，并用于表示噪声
    unique_labels = set(labels)
    colors = [pyplot.cm.cool(each) for each in numpy.linspace(0,1,len(unique_labels))]
    for k, col in zip(unique_labels, colors):
        if k == -1:
            #黑色用于表示噪音
            col = [0, 0, 0, 1]
        class_member_mask = (labels == k)
        xy = data[class_member_mask & core_samples_mask]
        pyplot.plot(xy[:,0], xy[:,1],'o',
                    markerfacecolor = tuple(col),
                    markeredgecolor = 'k', markersize = 14)
    pyplot.xlabel('Standard Scaled Ride Dist.')
    pyplot.ylabel('Standard Scaled Ride Time.')
    pyplot.title('Estimated number of clusters: %d' % n_clusters_)
    pyplot.savefig('taxi-rides.png')

