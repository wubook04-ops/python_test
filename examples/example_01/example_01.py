#定义模拟乘车数据的函数
def simulate_ride_distances():
    ride_dists = numpy.concatenate(
        (
            10 * numpy.random.random(size=370),
            30 * numpy.random.random(size=10), #较长的距离
            10 * numpy.random.random(size=10), #相同的距离
            10 * numpy.random.random(size=10) #相同的距离
        )
    )
    return ride_dists

def simulate_ride_speeds():
    ride_speeds = numpy.concatenate(
        (
            numpy.random.normal(loc=30, scale=5, size=370),
            numpy.random.normal(loc=30, scale=5, size=10),
            numpy.random.normal(loc=50, scale=10, size=10),
            numpy.random.normal(loc=15, scale=4, size=10)
        )
    )
    return ride_speeds

